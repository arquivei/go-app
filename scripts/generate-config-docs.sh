#!/usr/bin/env bash
set -euo pipefail

cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.."

# Ignore inherited application settings so malformed values cannot affect generation.
unset "${!APP_@}"

scratch=$(mktemp -d)
staged=''
cleanup() {
    if [[ -n "$staged" && -e "$staged" ]]; then
        unlink -- "$staged"
    fi
    find "$scratch" -maxdepth 1 -type f -delete
    rmdir -- "$scratch"
}
trap cleanup EXIT

# Keep build diagnostics out of the reference, including dependency downloads.
go build -o "$scratch/quickstart" ./examples/quickstart/

# uconfig writes formatted defaults to stderr before the app starts.
if ! "$scratch/quickstart" -app-config-output=env > /dev/null 2> "$scratch/defaults"; then
    cat "$scratch/defaults" >&2
    exit 1
fi
if [[ ! -s "$scratch/defaults" ]]; then
    printf '%s\n' 'No configuration defaults were generated.' >&2
    exit 1
fi

{
    cat <<'MARKDOWN'
# Configuration reference

Generated by `task docs:generate` from the quickstart's
`-app-config-output=env`. See the [configuration guide](configuration.md) for
how to override these defaults and the [operations guide](operations.md) for
admin endpoint behavior.

```dotenv
MARKDOWN
    cat "$scratch/defaults"
    printf '%s\n' '```'
} > "$scratch/reference"

# Stage beside the destination so the final rename stays on one filesystem.
staged=$(mktemp docs/.configuration-reference.XXXXXXXX)
cp -- "$scratch/reference" "$staged"
chmod 644 "$staged"
mv -f -- "$staged" docs/configuration-reference.md
